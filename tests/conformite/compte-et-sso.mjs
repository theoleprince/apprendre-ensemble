// Recette navigateur : mot de passe oublie (e-mail reel via Mailpit) + SSO OpenID Connect (Keycloak local).
import puppeteer from 'puppeteer-core';
import fs from 'node:fs';
const BASE = 'http://localhost:8088';
const OUT = './resultats/';
fs.mkdirSync(OUT, { recursive: true });
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
const results = [];
const ok = (name, cond, detail = '') => { results.push([name, !!cond, detail]); console.log(cond ? 'OK  ' : 'ECHEC', name, detail); };
const b = await puppeteer.launch({ executablePath: process.env.CHROME ?? 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: true });

// ---------- 1. Mot de passe oublie ----------
let ctx = await b.createBrowserContext();
let p = await ctx.newPage();
await p.goto(BASE + '/login', { waitUntil: 'networkidle0' });
await p.click('a[href="/mot-de-passe-oublie"]');
await p.waitForFunction(() => location.pathname === '/mot-de-passe-oublie');
await sleep(800);
await p.type('input[type=email]', 'parent@demo.local');
const before = (await (await fetch('http://localhost:8025/api/v1/messages')).json()).total;
await p.click('button[type=submit]');
await sleep(2500);
await p.screenshot({ path: OUT + '1-oubli.png' });
const msgs = (await (await fetch('http://localhost:8025/api/v1/messages')).json());
ok('e-mail de reinitialisation recu', msgs.total > before, `${msgs.total - before} nouveau(x)`);
const last = msgs.messages.find((m) => m.To[0].Address === 'parent@demo.local');
const full = await (await fetch(`http://localhost:8025/api/v1/message/${last.ID}`)).json();
const link = full.Text.match(/https?:\/\/\S+reinitialiser\?token=\S+/)?.[0];
ok('lien present dans l e-mail', !!link);
await p.goto(link, { waitUntil: 'networkidle0' });
await p.type('input[name=p1]', 'NouveauParent2026');
await p.type('input[name=p2]', 'NouveauParent2026');
await p.click('button[type=submit]');
await sleep(2000);
await p.screenshot({ path: OUT + '2-reinit.png' });
const login = await fetch(BASE + '/api/auth/login', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ email: 'parent@demo.local', password: 'NouveauParent2026' }) });
ok('connexion avec le nouveau mot de passe', login.status === 200, 'HTTP ' + login.status);
const oldPwd = await fetch(BASE + '/api/auth/login', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ email: 'parent@demo.local', password: 'Demo1234!' }) });
ok('ancien mot de passe refuse', oldPwd.status === 401, 'HTTP ' + oldPwd.status);
await p.goto(link, { waitUntil: 'networkidle0' });
await p.type('input[name=p1]', 'EncoreAutre2026'); await p.type('input[name=p2]', 'EncoreAutre2026');
await p.click('button[type=submit]'); await sleep(1500);
ok('lien a usage unique', (await p.content()).includes('invalide ou expiré'));
await ctx.close();

// ---------- 2. SSO ----------
ctx = await b.createBrowserContext();
p = await ctx.newPage();
await p.goto(BASE + '/login', { waitUntil: 'networkidle0' });
await sleep(800);
const ssoBtn = await p.$('a[href="/api/oauth2/authorization/sso"]');
ok('bouton SSO affiche', !!ssoBtn);
await Promise.all([p.waitForNavigation({ waitUntil: 'networkidle0' }), ssoBtn.click()]);
ok('redirection vers le fournisseur d identite', p.url().startsWith('http://keycloak.localhost:8180/realms/graines/'), p.url().slice(0, 70));
await p.screenshot({ path: OUT + '3-keycloak.png' });
await p.type('#username', 'enseignant.sso');
await p.type('#password', 'Sso-Test-2026');
await Promise.all([p.waitForNavigation({ waitUntil: 'networkidle0' }), p.click('#kc-login')]);
await p.waitForFunction(() => location.pathname.startsWith('/accueil'), { timeout: 20000 }).catch(() => {});
await sleep(1200);
await p.screenshot({ path: OUT + '4-retour-sso.png' });
ok('retour sur l application connecte', p.url().endsWith('/accueil'), p.url());
ok('jeton absent de l adresse', !p.url().includes('token='));
const user = await p.evaluate(() => JSON.parse(localStorage.getItem('formation.user') || 'null'));
ok('compte provisionne depuis l annuaire', user?.email === 'enseignant.sso@exemple.test' && user?.fullName === 'Adjoa Annuaire', JSON.stringify(user && { email: user.email, name: user.fullName, role: user.role }));
await ctx.close();
await b.close();
const failed = results.filter((r) => !r[1]).length;
console.log(`\n${results.length - failed}/${results.length} verifications reussies`);
process.exit(failed ? 1 : 0);
